def resource_text(name: str) -> str:
    """Read one packaged data file from ``vakr.defaults``.

    Args:
        name: File name, such as ``"options.toml"``.

    Returns:
        str: File contents.

    Raises:
        OSError: If the package data is missing, which is a packaging bug.
    """
    return files("vakr.defaults").joinpath(name).read_text(encoding="utf-8")


@cache
def catalog() -> Catalog:
    """Return vakr's option catalog, parsed once per process.

    Args:
        None

    Returns:
        Catalog: The packaged catalog.

    Raises:
        CatalogError: If the packaged catalog is malformed.
    """
    return parse_catalog(resource_text(CATALOG_FILE), f"vakr.defaults/{CATALOG_FILE}")


@cache
def migrations() -> tuple[Migration, ...]:
    """Return vakr's config migrations, parsed once per process.

    Args:
        None

    Returns:
        tuple[Migration, ...]: The full chain up to the catalog version.

    Raises:
        MigrationError: If the packaged migrations are malformed.
    """
    origin = f"vakr.defaults/{MIGRATIONS_FILE}"
    return parse_migrations(resource_text(MIGRATIONS_FILE), catalog().config_version, origin)


def layout(config_dir: Path) -> ConfigLayout:
    """Describe vakr's operator files under ``config_dir``.

    Args:
        config_dir: Normally ``/etc/vakr``.

    Returns:
        ConfigLayout: ``config.toml`` plus ``conf.d/*.toml``.

    Raises:
        None
    """
    return ConfigLayout(config_dir)


def inspect(config_dir: Path) -> LoadResult:
    """Load and validate the effective configuration with full provenance.

    Args:
        config_dir: Operator configuration directory.

    Returns:
        LoadResult: Values, sources, issues, and file versions.

    Raises:
        OSError: If an operator file exists but cannot be read.
    """
    return load_config(catalog(), migrations(), read_layers(layout(config_dir)))


def state_path(paths: InstallPaths) -> Path:
    """Locate the deployment-state file used by ``new-options``.

    Args:
        paths: Installation layout.

    Returns:
        Path: ``/var/lib/vakr/config-state.json``.

    Raises:
        None
    """
    return paths.state_dir / STATE_FILE


def backup_root(paths: InstallPaths) -> Path:
    """Locate the directory that receives timestamped configuration backups.

    Args:
        paths: Installation layout.

    Returns:
        Path: ``/var/lib/vakr/config-backups``.

    Raises:
        None
    """
    return paths.state_dir / BACKUP_DIR


def defaults_text() -> str:
    """Render the documented defaults file for ``/opt/vakr/share/defaults``.

    Args:
        None

    Returns:
        str: TOML text.

    Raises:
        None
    """
    return render_defaults(catalog(), DEFAULTS_HEADER)


def template_text() -> str:
    """Render the starter ``/etc/vakr/config.toml`` that ``postinst`` installs.

    Args:
        None

    Returns:
        str: TOML text containing only ``config_version`` plus comments.

    Raises:
        None
    """
    return render_template(catalog(), TEMPLATE_HEADER, TEMPLATE_HINTS, VERSION_NOTE)


def reference_markdown() -> str:
    """Render ``docs/operations/configuration.md``.

    Args:
        None

    Returns:
        str: Markdown text.

    Raises:
        None
    """
    return render_markdown(catalog(), DOC_TITLE, DOC_INTRO)
