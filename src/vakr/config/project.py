"""vakr's bindings for the portable ``configmerge`` library.

The library takes every project-specific value as a parameter (blueprint
section 29); this module supplies vakr's: the packaged catalog and
migrations, the ``/etc/vakr`` layout, where backups and deployment state
live, and the text of the generated defaults file, template, and reference
page. Everything else in vakr reaches configuration through here or through
``vakr.config.loader``.

Dependencies:
    importlib.resources: Reads the catalog from the installed package.
    vakr.lifecycle.configmerge: Layering, validation, rendering.
    vakr.paths: Installation layout.

Safety:
    Read-only. The catalog is parsed once per process and cached.

Example:
    >>> catalog().option("update.channel").default
    'prerelease'
"""

