def test_reply_without_our_magic_has_no_token() -> None:
    """A reply to someone else's ping, or with a cut payload, cannot match a probe.

    Args:
        None

    Returns:
        None

    Raises:
        None
    """
    header = wire.HEADER.pack(0, 0, 0, 1, 2)
    for payload in (b"ping" + TOKEN, wire.MAGIC + TOKEN[:3]):
        echo = wire.parse_echo(header + payload, 4)
        assert echo is not None
        assert echo.token is None


@PROPERTY
@given(st.binary(max_size=80), st.sampled_from([4, 6]))
def test_decoders_never_raise_on_arbitrary_bytes(data: bytes, version: int) -> None:
    """Property: any bytes from the network decode to a value or ``None``.

    Args:
        data: Arbitrary bytes.
        version: IP version.

    Returns:
        None

    Raises:
        None
    """
    wire.parse_echo(data, version)
    parse_raw(data, version, "192.0.2.1")
    parse_errqueue(data, [(*V4_RECVERR, data), (*V6_RECVERR, data)], None, version)


def test_arrival_stamp_is_read_from_scm_timestampns() -> None:
    """The kernel's arrival time lets a late read keep its true RTT.

    Args:
        None

    Returns:
        None

    Raises:
        None
    """
    stamp = struct.pack("=qq", 1_700_000_000, 250)
    assert wire.arrival_ns([(socket.SOL_SOCKET, wire.SO_TIMESTAMPNS, stamp)]) == (
        1_700_000_000_000_000_250
    )
    assert wire.arrival_ns([]) is None
    assert wire.arrival_ns([(socket.SOL_SOCKET, wire.SO_TIMESTAMPNS, b"\x00")]) is None


def test_errqueue_host_unreachable_names_the_router() -> None:
    """A router's "host unreachable" resolves the probe with who said it.

    Args:
        None

    Returns:
        None

    Raises:
        None
    """
    request = wire.echo_request(SocketKind.DATAGRAM, 4, 0, 7, TOKEN)
    anc = [(*V4_RECVERR, ext_err(2, 3, 1, "198.51.100.1", errno.EHOSTUNREACH))]
    target = socket.inet_aton("192.0.2.9")
    error = parse_errqueue(request, anc, target, 4)
    assert error == IcmpError(7, TOKEN, target, "host unreachable", "198.51.100.1")


def test_errqueue_ipv6_and_truncated_quote_still_match_by_sequence() -> None:
    """ICMP-011: ICMPv6 errors decode; an 8-byte quote keeps the sequence number.

    Args:
        None

    Returns:
        None

    Raises:
        None
    """
    request = wire.echo_request(SocketKind.DATAGRAM, 6, 0, 99, TOKEN)[:8]
    anc = [(*V6_RECVERR, ext_err(3, 1, 3, "2001:db8::1"))]
    error = parse_errqueue(request, anc, None, 6)
    assert error is not None
    assert (error.seq, error.token, error.reason, error.reporter) == (
        99,
        None,
        "address unreachable",
        "2001:db8::1",
    )


def test_errqueue_local_error_is_flagged_local() -> None:
    """A local-origin error means the packet never left this host.

    Args:
        None

    Returns:
        None

    Raises:
        None
    """
    request = wire.echo_request(SocketKind.DATAGRAM, 4, 0, 3, TOKEN)
    anc = [(*V4_RECVERR, ext_err(1, 0, 0, None, errno.EMSGSIZE))]
    error = parse_errqueue(request, anc, None, 4)
    assert error is not None
    assert error.local
    assert error.reporter is None
    assert "Message too long" in error.reason


@pytest.mark.parametrize(
    ("anc_factory", "data"),
    [
        pytest.param(
            lambda: [(*V4_RECVERR, ext_err(2, 5, 1, "198.51.100.1"))], None, id="redirect"
        ),
        pytest.param(lambda: [], None, id="no control message"),
        pytest.param(lambda: [(*V4_RECVERR, b"\x00" * 4)], None, id="short control message"),
        pytest.param(lambda: [(*V4_RECVERR, ext_err(4, 0, 0, None))], None, id="tx status"),
        pytest.param(
            lambda: [(*V4_RECVERR, ext_err(2, 3, 1, None))], b"\x00" * 8, id="not a request"
        ),
    ],
)
def test_errqueue_entries_that_are_not_failures_decode_to_none(
    anc_factory: Callable[[], list[tuple[int, int, bytes]]], data: bytes | None
) -> None:
    """Redirects, malformed entries, and non-ICMP origins never resolve a probe.

    Args:
        anc_factory: Builds the control messages.
        data: Quoted bytes; a valid request when ``None``.

    Returns:
        None

    Raises:
        None
    """
    quoted = data if data is not None else wire.echo_request(SocketKind.DATAGRAM, 4, 0, 1, TOKEN)
    assert parse_errqueue(quoted, anc_factory(), None, 4) is None


