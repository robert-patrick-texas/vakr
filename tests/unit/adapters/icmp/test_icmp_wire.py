@pytest.mark.parametrize("version", [4, 6])
def test_reply_round_trip_keeps_sequence_and_token(version: int) -> None:
    """ICMP-011: replies decode the same way for both families.

    Args:
        version: IP version.

    Returns:
        None

    Raises:
        None
    """
    request = wire.echo_request(SocketKind.DATAGRAM, version, 0, 4242, TOKEN)
    assert wire.parse_echo(echo_reply(request), version) == wire.Echo(0x4D2, 4242, TOKEN)


