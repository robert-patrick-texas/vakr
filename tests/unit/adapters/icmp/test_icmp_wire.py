def test_raw_ipv4_reply_skips_the_ip_header() -> None:
    """Raw IPv4 reads start with the IP header, which must be skipped.

    Args:
        None

    Returns:
        None

    Raises:
        None
    """
    request = wire.echo_request(SocketKind.RAW, 4, 77, 5, TOKEN)
    packet = ipv4_header("192.0.2.9", "192.0.2.1") + echo_reply(request, ident=77)
    assert parse_raw(packet, 4, "192.0.2.9") == wire.Echo(77, 5, TOKEN)
    assert parse_raw(b"\x60" + bytes(30), 4, None) is None  # not IPv4
    assert parse_raw(ipv4_header("192.0.2.9", "192.0.2.1") + b"\x00", 4, None) is None


def test_raw_errors_find_the_quoted_request() -> None:
    """Raw sockets receive ICMP errors as packets quoting our request.

    Args:
        None

    Returns:
        None

    Raises:
        None
    """
    request = wire.echo_request(SocketKind.RAW, 4, 77, 6, TOKEN)
    quoted = ipv4_header("192.0.2.1", "192.0.2.9") + request[:8]
    packet = ipv4_header("198.51.100.1", "192.0.2.1") + bytes([11, 0, 0, 0, 0, 0, 0, 0]) + quoted
    error = parse_raw(packet, 4, "198.51.100.1")
    assert isinstance(error, IcmpError)
    assert (error.seq, error.ident, error.reason) == (6, 77, "time exceeded in transit")
    assert error.target == socket.inet_aton("192.0.2.9")
    request6 = wire.echo_request(SocketKind.RAW, 6, 78, 8, TOKEN)
    packet6 = bytes([1, 3, 0, 0, 0, 0, 0, 0]) + ipv6_header("2001:db8::9") + request6
    error6 = parse_raw(packet6, 6, "2001:db8::1")
    assert isinstance(error6, IcmpError)
    assert (error6.seq, error6.ident, error6.token, error6.reason) == (
        8,
        78,
        TOKEN,
        "address unreachable",
    )


@pytest.mark.parametrize(
    ("version", "packet"),
    [
        pytest.param(4, bytes([3, 1]) + bytes(6) + bytes(10), id="quote too short"),
        pytest.param(
            4,
            bytes([3, 1]) + bytes(6) + ipv4_header("192.0.2.1", "192.0.2.9", 17) + bytes(8),
            id="quote is UDP",
        ),
        pytest.param(6, bytes([1, 0]) + bytes(6) + ipv6_header("2001:db8::9", 17), id="quote UDP"),
        pytest.param(6, bytes([128, 0]) + bytes(6), id="someone else's request"),
        pytest.param(6, b"\x81", id="too short"),
    ],
)
def test_unrelated_raw_traffic_is_ignored(version: int, packet: bytes) -> None:
    """Raw sockets see all ICMP on the host; anything not about our probes is dropped.

    Args:
        version: IP version.
        packet: ICMP message (IPv4 header added below).

    Returns:
        None

    Raises:
        None
    """
    data = (ipv4_header("198.51.100.1", "192.0.2.1") + packet) if version == 4 else packet
    assert parse_raw(data, version, "198.51.100.1") is None
