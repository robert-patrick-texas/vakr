"""API-T01, API-T05, API-008: the checked-in OpenAPI document matches the code.

``docs/api/openapi.json`` is generated by ``make openapi``; this test fails
when it is stale, so the published contract and the running API cannot
drift. The document is deterministic, names the API version rather than
the release (VER-001), describes the cookie and kiosk schemes, marks the
anonymous endpoints, and exposes no row IDs.

Dependencies:
    vakr.api.openapi; the CLI entry point.

Example:
    $ uv run pytest tests/unit/api/test_api_openapi.py
"""

import functools
import json
from pathlib import Path

import pytest

from vakr.api import openapi
from vakr.api.openapi import ANONYMOUS_PATHS
from vakr.cli.main import main
from vakr.version import get_version

REPO = Path(__file__).resolve().parents[3]
CHECKED_IN = REPO / "docs/api/openapi.json"
TEXT = functools.cache(openapi.openapi_text)  # generating takes about a second
UUID_TEXT_FIELDS = {("SearchHit", "id")}
"""Identifiers typed as text that hold UUID text (a provider hit has none)."""


def test_api_t01_checked_in_schema_matches_the_code() -> None:
    """API-T01, API-008: regenerate with ``make openapi`` when this fails.

    Args:
        None

    Returns:
        None

    Raises:
        None
    """
    assert CHECKED_IN.read_text(encoding="utf-8") == TEXT()
    assert openapi.openapi_text() == TEXT()  # deterministic


def test_api008_document_describes_versions_security_and_errors() -> None:
    """API-004, API-007, API-008: v1 paths, error envelope, security schemes, no release number.

    Args:
        None

    Returns:
        None

    Raises:
        None
    """
    document = json.loads(TEXT())
    assert document["info"]["version"] == "1"
    assert get_version() not in json.dumps(document["info"])
    schemes = set(document["components"]["securitySchemes"])
    assert schemes == {"sessionCookie", "kioskToken", "kioskCookie", "replicationToken"}
    assert all(p.startswith("/api/v1/") for p in document["paths"])
    for path, operations in document["paths"].items():
        for operation in operations.values():
            if path.startswith("/api/v1/replication/"):  # MPOS-006: the replication token only
                assert operation["security"] == [{"replicationToken": []}], path
                continue
            assert ("security" in operation) == (path in ANONYMOUS_PATHS), path
            assert "Args:" not in operation.get("description", "")
            if "401" in operation["responses"]:
                ref = operation["responses"]["401"]["content"]["application/json"]["schema"]
                assert ref["$ref"].endswith("/ErrorEnvelope")


def test_api_t05_no_row_ids_in_the_contract() -> None:
    """API-T05, API-002: every identifier field in a schema is a UUID string.

    Args:
        None

    Returns:
        None

    Raises:
        None
    """
    schemas = json.loads(TEXT())["components"]["schemas"]
    for name, schema in schemas.items():
        for field, spec in schema.get("properties", {}).items():
            assert field.lower() not in ("rowid", "row_id", "pk")
            exempt = (name, field) in UUID_TEXT_FIELDS or field in ("request_id", "circuit_id")
            if (field == "id" or field.endswith("_id")) and not exempt:
                text = json.dumps(spec)
                assert '"format": "uuid"' in text, (name, field)


def test_cli_writes_and_checks_the_schema(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
) -> None:
    """API-008: ``vakr api openapi`` prints, writes, and checks the document.

    Args:
        tmp_path: Test directory.
        capsys: Output capture.
        monkeypatch: Reuses the generated text.

    Returns:
        None

    Raises:
        None
    """
    monkeypatch.setattr(openapi, "openapi_text", TEXT)
    target = tmp_path / "openapi.json"
    assert main(["api", "openapi", "--output", str(target), "--check"]) == 1
    assert "out of date" in capsys.readouterr().err
    assert main(["api", "openapi", "--output", str(target)]) == 0
    assert main(["api", "openapi", "--output", str(target), "--check"]) == 0
    assert main(["api", "openapi"]) == 0
    assert json.loads(capsys.readouterr().out)["openapi"].startswith("3.")
