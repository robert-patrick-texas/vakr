"""CLI: ``vakr kiosk create|list|revoke`` (UI-013, E.12, SEC-018, CRED-002).

Runs the real commands against a relocated install (``VAKR_ROOT``) with a
migrated SQLite metadata database. Each token is generated by the command
under test; afterwards every later output, every audit row, every log
record, and the raw database files are searched for it (CRED-002).

Dependencies:
    pytest; vakr.cli.main; the SQLite metadata adapter.

Example:
    $ uv run pytest tests/unit/auth/test_kiosk_cli.py
"""

import json
import logging
import re
from pathlib import Path

import pytest

from tests.unit.auth.test_user_cli import _leaks, _run
from vakr.adapters.sqlite.metadata import (
    METADATA_FILE,
    SqliteMetadataStore,
    metadata_migrations,
    sqlite_uow_factory,
)
from vakr.domain.paging import PageRequest

TOKEN = re.compile(r"vkk_[A-Za-z0-9_-]+")


def _audit_rows(root: Path) -> list[tuple[str, str]]:
    """Return ``(action, actor)`` of every audit row, oldest first.

    Args:
        root: Install root.

    Returns:
        list[tuple[str, str]]: The rows.

    Raises:
        None
    """
    store = SqliteMetadataStore(root / "var/lib/vakr" / METADATA_FILE)
    with sqlite_uow_factory(store)() as uow:
        events = uow.audit.list_page(PageRequest(limit=500)).items
    store.close()
    return [(e.action, e.actor) for e in reversed(events)]


@pytest.fixture
def root(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """Relocate the install and migrate an empty metadata database.

    Args:
        tmp_path: Install root.
        monkeypatch: Sets ``VAKR_ROOT`` and a sudo-like environment.

    Returns:
        Path: The install root.

    Raises:
        None
    """
    monkeypatch.setenv("VAKR_ROOT", str(tmp_path))
    for name in ("LOGNAME", "USER"):
        monkeypatch.setenv(name, "root")
    monkeypatch.setenv("SUDO_USER", "opsadmin")
    (tmp_path / "var/lib/vakr").mkdir(parents=True)
    metadata_migrations(tmp_path / "var/lib/vakr" / METADATA_FILE).migrate()
    return tmp_path


def test_ui013_create_prints_the_token_once_and_nothing_else_ever_does(
    root: Path, capsys: pytest.CaptureFixture[str], caplog: pytest.LogCaptureFixture
) -> None:
    """UI-013, CRED-002: the token is in create's output only; list, JSON, logs, audit never.

    Args:
        root: The install.
        capsys: Output capture.
        caplog: Log capture.

    Returns:
        None

    Raises:
        None
    """
    caplog.set_level(logging.DEBUG)
    code, out = _run(capsys, "kiosk", "create", "noc-wall", "--lifetime", "90d")
    assert code == 0
    tokens = TOKEN.findall(out)
    assert len(tokens) == 1
    token = tokens[0]
    assert "/kiosk/setup" in out
    assert "sudo vakr kiosk revoke noc-wall" in out
    later = [_run(capsys, "kiosk", "list")[1], _run(capsys, "kiosk", "list", "--json")[1]]
    assert all(token not in text for text in later)
    rows = json.loads(later[1])["kiosk_tokens"]
    assert [(r["label"], r["live"], r["created_by"]) for r in rows] == [
        ("noc-wall", True, "cli:opsadmin (sudo)")
    ]
    assert "token" not in rows[0]
    assert "token_hash" not in rows[0]
    assert "noc-wall" in later[0]
    assert "never" in later[0]
    assert token not in caplog.text
    assert _leaks(root, [token]) == []


def test_e12_revoke_by_label_and_by_id_with_audit(
    root: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """E.12, SEC-018: revoke takes a label or an ID; both are audited with the OS user.

    Args:
        root: The install.
        capsys: Output capture.

    Returns:
        None

    Raises:
        None
    """
    _run(capsys, "kiosk", "create", "lobby tv")
    _run(capsys, "kiosk", "create", "wall-2")
    rows = json.loads(_run(capsys, "kiosk", "list", "--json")[1])["kiosk_tokens"]
    by_id = next(r["id"] for r in rows if r["label"] == "wall-2")
    assert _run(capsys, "kiosk", "revoke", "lobby tv")[0] == 0
    code, out = _run(capsys, "kiosk", "revoke", by_id)
    assert code == 0
    assert "revoked kiosk token wall-2" in out
    assert json.loads(_run(capsys, "kiosk", "list", "--json")[1])["kiosk_tokens"] == []
    code, out = _run(capsys, "kiosk", "revoke", "lobby tv")
    assert code == 1
    assert "no kiosk token lobby tv" in out
    actions = [(a, actor) for a, actor in _audit_rows(root) if a.startswith("kiosk.")]
    assert actions.count(("kiosk.revoke", "cli:opsadmin (sudo)")) == 2


@pytest.mark.usefixtures("root")
def test_e12_refusals_exit_1_and_never_echo_a_pasted_token(
    capsys: pytest.CaptureFixture[str],
) -> None:
    """E.12: label rule, taken label, lifetime range; a token given to revoke is not repeated.

    Args:
        capsys: Output capture.

    Returns:
        None

    Raises:
        None
    """
    code, out = _run(capsys, "kiosk", "create", "wall")
    token = TOKEN.findall(out)[0]
    assert _run(capsys, "kiosk", "create", "wall")[0] == 1
    assert _run(capsys, "kiosk", "create", "--", "-bad")[0] == 1
    assert _run(capsys, "kiosk", "create", "tab\there")[0] == 1
    assert _run(capsys, "kiosk", "create", "short", "--lifetime", "1h")[0] == 1
    assert _run(capsys, "kiosk", "create", "long", "--lifetime", "2y")[0] == 1
    code, out = _run(capsys, "kiosk", "revoke", token)
    assert code == 1
    assert token not in out
    assert "that is a kiosk token" in out
    assert _run(capsys, "kiosk")[0] == 2


def test_storage_unavailable_exits_4(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    """Exit 4 when there is no metadata database, as ``vakr user``.

    Args:
        tmp_path: An install without a database.
        monkeypatch: Sets ``VAKR_ROOT``.
        capsys: Output capture.

    Returns:
        None

    Raises:
        None
    """
    monkeypatch.setenv("VAKR_ROOT", str(tmp_path))
    assert _run(capsys, "kiosk", "list")[0] == 4
