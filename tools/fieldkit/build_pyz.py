"""Build the field kit as one reproducible zipapp (FIELD-001).

Operators run the field kit on production hosts that may not have vakr, git,
or this repository, so it ships as a single ``vakr-fieldkit.pyz``: the
standard-library ``fieldkit*.py`` modules, a generated ``__main__.py``, and a
generated ``fieldkit_embedded.py`` holding the project values from
``fieldkit.toml``, the version from the single ``VERSION`` file (VER-001),
and the development host's recipient certificate. Packaging calls this at
build time and installs the result at
``/opt/vakr/share/fieldkit/vakr-fieldkit.pyz``; releases attach it too.

The archive follows the ``zipapp`` layout (shebang line plus a ZIP with
``__main__.py``) but is written with ``zipfile`` directly, because
``zipapp.create_archive`` stamps entries with local-time file mtimes. Fixed
timestamps, permissions, and member order make two builds from the same
sources byte-identical.

Dependencies:
    tomllib, zipfile: Standard library only.

Safety:
    Only the public recipient certificate is embedded; the build refuses a
    file that contains a private key. Test modules are never packaged. The
    output is written to a temporary name and renamed into place.

Example:
    $ uv run tools/fieldkit/build_pyz.py --output dist/vakr-fieldkit.pyz
    build_pyz: wrote dist/vakr-fieldkit.pyz (vakr-fieldkit 1.2.3, 18 modules)
"""

import argparse
import io
import sys
import tomllib
import zipfile
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
ZIP_EPOCH = (1980, 1, 1, 0, 0, 0)
MAIN_TEMPLATE = '''"""Zipapp entry point for {tool}; generated by build_pyz.py, do not edit."""

import sys

if sys.version_info < {python!r}:
    sys.exit("{tool} needs Python {dotted} or newer; run: uv run --python {dotted} " + sys.argv[0])

from fieldkit import main

sys.exit(main())
'''


def load_config(path: Path) -> dict[str, Any]:
    """Read ``fieldkit.toml``.

    Args:
        path: Configuration file.

    Returns:
        dict[str, Any]: Parsed TOML.

    Raises:
        OSError: If the file cannot be read.
        tomllib.TOMLDecodeError: If it is not valid TOML.
    """
    with path.open("rb") as handle:
        return tomllib.load(handle)


def build_values(config: dict[str, Any], base: Path, recipient: Path | None) -> dict[str, Any]:
    """Compute the ``BUILD`` mapping embedded in the zipapp.

    Args:
        config: Parsed ``fieldkit.toml``.
        base: Directory that relative paths in the config are resolved from.
        recipient: Override for the recipient certificate, or ``None``.

    Returns:
        dict[str, Any]: Values matching ``fieldkit_run.BuildInfo`` fields.

    Raises:
        OSError: If the version file or certificate cannot be read.
        ValueError: If the certificate file is not a lone public certificate.
    """
    kit, app = config["fieldkit"], config["fieldkit"].get("app", {})
    pem = (recipient or base / kit["recipient"]).read_text(encoding="ascii")
    if "PRIVATE KEY" in pem or "BEGIN CERTIFICATE" not in pem:
        raise ValueError("the recipient file must hold only a PEM certificate")
    return {
        "tool_name": kit["tool_name"],
        "version": (base / kit["version_file"]).read_text(encoding="utf-8").strip(),
        "bundle_prefix": kit["bundle_prefix"],
        "app_name": app.get("name", ""),
        "app_commands": [list(c) for c in app.get("commands", [])],
        "app_units": list(app.get("units", [])),
        "acceptance_command": list(kit.get("acceptance", {}).get("command", [])),
        "keep_keywords": list(kit.get("keep_keywords", [])),
        "egress_get": list(kit.get("egress_get", [])),
        "egress_head": list(kit.get("egress_head", [])),
        "recipient_pem": pem,
        "inbox_hint": kit.get("inbox_hint", "the development host"),
    }


def archive_entries(source: Path, values: dict[str, Any], python: str) -> dict[str, bytes]:
    """Collect the files that go into the zipapp.

    Args:
        source: Directory holding the ``fieldkit*.py`` modules.
        values: Embedded build values.
        python: Minimum Python version such as ``"3.15"``.

    Returns:
        dict[str, bytes]: Archive path to content.

    Raises:
        OSError: If a module cannot be read.
    """
    version = tuple(int(part) for part in python.split("."))
    main = MAIN_TEMPLATE.format(tool=values["tool_name"], python=version, dotted=python)
    embedded = '"""Build values; generated by build_pyz.py, do not edit."""\n\n'
    embedded += f"BUILD = {values!r}\n"
    entries = {"__main__.py": main.encode(), "fieldkit_embedded.py": embedded.encode()}
    for module in sorted(source.glob("fieldkit*.py")):
        if module.name != "fieldkit_embedded.py":
            entries[module.name] = module.read_bytes()
    return entries


def write_pyz(entries: dict[str, bytes], output: Path, interpreter: str) -> None:
    """Write a byte-reproducible zipapp.

    Args:
        entries: Archive path to content.
        output: Destination ``.pyz``.
        interpreter: Shebang interpreter, such as ``/usr/bin/env python3``.

    Returns:
        None

    Raises:
        OSError: If the file cannot be written.
    """
    buffer = io.BytesIO()
    buffer.write(f"#!{interpreter}\n".encode())
    with zipfile.ZipFile(buffer, "w") as archive:
        for name in sorted(entries):
            info = zipfile.ZipInfo(name, date_time=ZIP_EPOCH)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 3  # Unix, so the permission bits below are honoured
            info.external_attr = 0o644 << 16
            archive.writestr(info, entries[name], compresslevel=9)
    output.parent.mkdir(parents=True, exist_ok=True)
    partial = output.with_name(output.name + ".partial")
    partial.write_bytes(buffer.getvalue())
    partial.chmod(0o755)
    partial.replace(output)


def main(argv: list[str] | None = None) -> int:
    """Build the zipapp.

    Args:
        argv: Arguments without the program name.

    Returns:
        int: 0 on success, 1 on a configuration or input error.

    Raises:
        None
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, required=True, metavar="FILE")
    parser.add_argument("--config", type=Path, default=HERE / "fieldkit.toml", metavar="TOML")
    parser.add_argument("--recipient", type=Path, metavar="CERT", help="override the certificate")
    parser.add_argument("--interpreter", default="/usr/bin/env python3")
    args = parser.parse_args(argv)
    try:
        config = load_config(args.config)
        values = build_values(config, args.config.resolve().parent, args.recipient)
        python = config["fieldkit"].get("python", "3.15")
        entries = archive_entries(HERE, values, python)
        write_pyz(entries, args.output, args.interpreter)
    except (OSError, ValueError, KeyError, tomllib.TOMLDecodeError) as exc:
        print(f"build_pyz: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1
    built = f"{values['tool_name']} {values['version']}, {len(entries) - 1} modules"
    print(f"build_pyz: wrote {args.output} ({built})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
