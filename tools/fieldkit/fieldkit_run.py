"""Bounded external commands, step timing, and build information for the field kit.

The field kit runs on production monitoring hosts that the developers cannot
log in to. Every external program it calls (``snmpbulkwalk``, ``ping``,
``journalctl``, ``openssl``) can hang on an unreachable device or a stuck
service, so each call has a hard timeout and an output cap, and each
collection step records its duration and error in the bundle manifest
instead of aborting the run (FIELD-003, FIELD-009).

Dependencies:
    subprocess: Commands run from argument lists, never through a shell
        (FIELD-001).
    importlib: Loads ``fieldkit_embedded``, the module ``build_pyz.py``
        generates inside the zipapp with project values and the default
        recipient certificate.

Safety:
    Commands receive no standard input, so nothing can block on a prompt.
    Error text recorded for a step is the exception's message only; callers
    never format credentials into exceptions.

Example:
    >>> run_command(["true"], timeout=5).returncode
    0
"""

import importlib
import subprocess
import sys
import time
from collections.abc import Generator, Mapping, Sequence
from contextlib import contextmanager
from dataclasses import dataclass, field
from typing import Any

DEFAULT_OUTPUT_CAP = 32 * 1024 * 1024
"""Largest captured stdout per command; one walk of a large switch is ~5 MB."""


@dataclass(frozen=True, slots=True)
class BuildInfo:
    """Project values baked into the zipapp by ``build_pyz.py`` (section 29.1).

    Attributes:
        tool_name: Program name, also the ``~/.config/<tool_name>/`` directory.
        version: Tool version from the project's single version file.
        bundle_prefix: Bundle files are ``<prefix>-<host>-<UTC>.tar.gz``.
        app_name: Installed application's command and profile name, or ``""``.
        app_commands: Argument lists run by the application profile.
        app_units: journald unit globs read by the application profile.
        keep_keywords: Description keywords kept verbatim when pseudonymizing.
        egress_get: URLs fetched with GET by the reachability test.
        egress_head: URLs requested with HEAD by the reachability test.
        recipient_pem: Default recipient certificate (PEM), or ``""``.
        inbox_hint: Where the development host expects bundles, for the
            final "next step" line.
    """

    tool_name: str = "fieldkit"
    version: str = "0+source"
    bundle_prefix: str = "field"
    app_name: str = ""
    app_commands: tuple[tuple[str, ...], ...] = ()
    app_units: tuple[str, ...] = ()
    keep_keywords: tuple[str, ...] = ()
    egress_get: tuple[str, ...] = ()
    egress_head: tuple[str, ...] = ()
    recipient_pem: str = ""
    inbox_hint: str = "the development host's field inbox"


def load_build_info(module_name: str = "fieldkit_embedded") -> BuildInfo:
    """Return the embedded build information, or neutral defaults from source.

    Args:
        module_name: Module generated by ``build_pyz.py``.

    Returns:
        BuildInfo: Values from the zipapp, or defaults when running the
        sources directly (tests and development).

    Raises:
        None
    """
    try:
        values: dict[str, Any] = dict(importlib.import_module(module_name).BUILD)
    except ModuleNotFoundError:
        return BuildInfo()
    for key, value in values.items():
        if isinstance(value, list):
            values[key] = tuple(tuple(v) if isinstance(v, list) else v for v in value)
    return BuildInfo(**values)


@dataclass(frozen=True, slots=True)
class CommandResult:
    """Outcome of one external command.

    Attributes:
        argv: The argument list that was run.
        returncode: Exit status, or ``None`` if it never ran or timed out.
        stdout: Decoded standard output, possibly truncated.
        stderr: Decoded standard error, possibly truncated.
        seconds: Wall-clock duration.
        error: Why the command failed to run or finish, else ``None``.
        truncated: Whether stdout was cut at the output cap.
    """

    argv: tuple[str, ...]
    returncode: int | None
    stdout: str
    stderr: str
    seconds: float
    error: str | None = None
    truncated: bool = False

    @property
    def ok(self) -> bool:
        """Report whether the command ran to completion with status 0.

        Args:
            None

        Returns:
            bool: ``True`` for a clean exit.

        Raises:
            None
        """
        return self.error is None and self.returncode == 0


def _decode(data: bytes | str | None, cap: int) -> tuple[str, bool]:
    """Decode captured output and cut it at ``cap`` bytes.

    Args:
        data: Raw output from subprocess, possibly ``None``.
        cap: Maximum bytes kept.

    Returns:
        tuple[str, bool]: Text and whether it was truncated.

    Raises:
        None
    """
    raw = data.encode() if isinstance(data, str) else (data or b"")
    return raw[:cap].decode("utf-8", errors="replace"), len(raw) > cap


def run_command(
    argv: Sequence[str],
    timeout: float,
    env: Mapping[str, str] | None = None,
    output_cap: int = DEFAULT_OUTPUT_CAP,
    umask: int = -1,
) -> CommandResult:
    """Run one program from an argument list with a hard timeout.

    Args:
        argv: Program and arguments; never interpreted by a shell.
        timeout: Seconds before the process is killed.
        env: Complete environment for the child, or ``None`` to inherit.
        output_cap: Maximum stdout bytes kept.
        umask: File-creation mask applied in the child only; ``-1`` inherits.

    Returns:
        CommandResult: Exit status, output, and duration. Missing programs and
        timeouts are reported in ``error`` instead of raising.

    Raises:
        None
    """
    start = time.monotonic()
    try:
        # Argument lists only (FIELD-001); stdin is closed so nothing can prompt.
        proc = subprocess.run(  # noqa: S603 - argv is built by the field kit, no shell
            list(argv),
            capture_output=True,
            stdin=subprocess.DEVNULL,
            timeout=timeout,
            env=None if env is None else dict(env),
            check=False,
            umask=umask,
        )
    except FileNotFoundError:
        return CommandResult(tuple(argv), None, "", "", 0.0, f"{argv[0]}: not installed")
    except subprocess.TimeoutExpired as exc:
        out, cut = _decode(exc.stdout, output_cap)
        err, _ = _decode(exc.stderr, output_cap)
        seconds = time.monotonic() - start
        return CommandResult(
            tuple(argv), None, out, err, seconds, f"timed out after {timeout:g}s", cut
        )
    out, cut = _decode(proc.stdout, output_cap)
    err, _ = _decode(proc.stderr, output_cap)
    return CommandResult(
        tuple(argv), proc.returncode, out, err, time.monotonic() - start, None, cut
    )


@dataclass
class StepLog:
    """Per-step timings and errors for the manifest (FIELD-003).

    Not thread-safe; the field kit runs steps sequentially on purpose so it
    never loads a device's control plane with parallel requests.

    Attributes:
        steps: One record per finished step, in run order.
        deadline: ``time.monotonic()`` value after which steps are skipped.
    """

    steps: list[dict[str, Any]] = field(default_factory=list)
    deadline: float = float("inf")

    def expired(self) -> bool:
        """Report whether the overall time budget is used up (FIELD-009).

        Args:
            None

        Returns:
            bool: ``True`` once the deadline has passed.

        Raises:
            None
        """
        return time.monotonic() >= self.deadline

    @contextmanager
    def step(self, name: str) -> Generator[dict[str, Any]]:
        """Time one step; record, rather than propagate, its failure.

        Args:
            name: Stable step name such as ``"snmp.rtr1.system"``.

        Returns:
            Generator[dict[str, Any]]: The step record; the body may add keys
            such as ``"error"`` or ``"note"``.

        Raises:
            None
        """
        record: dict[str, Any] = {"name": name, "error": None}
        start = time.monotonic()
        try:
            yield record
        # One failed step must not lose everything already collected.
        except Exception as exc:  # noqa: BLE001
            record["error"] = f"{type(exc).__name__}: {exc}"
        record["seconds"] = round(time.monotonic() - start, 3)
        self.steps.append(record)

    def errors(self) -> list[str]:
        """List ``"step: error"`` strings for every failed step.

        Args:
            None

        Returns:
            list[str]: Error lines in run order.

        Raises:
            None
        """
        return [f"{s['name']}: {s['error']}" for s in self.steps if s.get("error")]


def progress(tool: str, message: str) -> None:
    """Print a progress line on stderr, keeping stdout for the final line.

    Args:
        tool: Program name used as the line prefix.
        message: Operator-readable text without secrets.

    Returns:
        None

    Raises:
        None
    """
    print(f"{tool}: {message}", file=sys.stderr, flush=True)
